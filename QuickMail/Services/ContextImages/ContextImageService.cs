using System;
using System.Collections.Concurrent;
using System.Collections.Generic;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using QuickMail.Models;

namespace QuickMail.Services.ContextImages;

/// <summary>
/// MailBox MatriX contextual images, step 3: the picture for a message row. Classifies once (sender and
/// subject only — <see cref="ContextImageClassifier"/>), remembers the choice in
/// <see cref="ContextImageStore"/>, and answers with the bundled picture's URI or null for the
/// neutral row. Nothing leaves the computer; nothing here can delay reading, sending or syncing
/// mail — every failure degrades to the neutral row.
/// </summary>
public sealed class ContextImageService : IDisposable
{
    /// <summary>Pictures per category in Assets/ContextImages (category-1.jpg, category-2.jpg).</summary>
    public const int VariantsPerCategory = 2;
    public const string BundledSource = "bundled";
    public const string BundledLicence = "MailBox MatriX original artwork (MIT), generated by Tools/MailBoXX.ArtGen";

    private readonly ContextImageStore? _store;
    private readonly string _assetUriPrefix;
    private readonly ConcurrentDictionary<string, ContextImageChoice> _choices = new(StringComparer.Ordinal);
    private readonly ConcurrentQueue<ContextImageChoice> _pendingSaves = new();
    private readonly Timer _saveTimer;
    private readonly Task _loadTask;
    private int _saving;

    /// <param name="store">Persistence; null runs in memory only (tests, or a store that failed to open).</param>
    /// <param name="assemblyName">Assembly holding the bundled pictures (for the pack URI).</param>
    public ContextImageService(ContextImageStore? store, string assemblyName)
    {
        _store = store;
        _assetUriPrefix = $"pack://application:,,,/{assemblyName};component/Assets/ContextImages/";
        _saveTimer = new Timer(_ => FlushPendingSaves(), null, Timeout.Infinite, Timeout.Infinite);
        _loadTask = _store is null ? Task.CompletedTask : Task.Run(LoadStored);
    }

    /// <summary>When false every row is neutral (Settings: "Pictures behind messages").</summary>
    public bool Enabled { get; set; } = true;

    /// <summary>The stored choice for a message key, if any (exposed for tests and diagnostics).</summary>
    public ContextImageChoice? GetChoice(string messageKey) => _choices.TryGetValue(messageKey, out var c) ? c : null;

    /// <summary>The picture URI for a message row, or null for the neutral row.</summary>
    /// <param name="imagerySet">"light" or "dark" — the theme's picture set (Theme.ImagerySet).</param>
    public string? ResolveImageUri(MailMessageSummary message, string imagerySet = "light")
    {
        if (!Enabled) return null;
        try
        {
            var key = KeyFor(message);
            if (!_choices.TryGetValue(key, out var choice) || choice.SelectorVersion != ContextImageClassifier.Version)
            {
                var (category, rule) = ContextImageClassifier.Classify(message.From, message.Subject);
                choice = new ContextImageChoice(key, category,
                    category is null ? 0 : ContextImageClassifier.Variant(key, VariantsPerCategory),
                    BundledSource, rule, BundledLicence, ContextImageClassifier.Version, DateTime.UtcNow.Ticks);
                _choices[key] = choice;
                _pendingSaves.Enqueue(choice);
                _saveTimer.Change(1500, Timeout.Infinite);   // batch writes off the UI thread
            }
            var set = imagerySet == "dark" ? "dark" : "light";
            return choice.Category is null ? null : $"{_assetUriPrefix}{set}/{choice.Category}-{choice.Variant}.jpg";
        }
        catch (Exception ex)
        {
            LogService.Debug($"ContextImageService: neutral row after {ex.GetType().Name}");
            return null;
        }
    }

    /// <summary>
    /// Identity that survives folder moves and Gmail labels: account + RFC Message-ID, falling back
    /// to the per-folder UID when the server gave no Message-ID.
    /// </summary>
    public static string KeyFor(MailMessageSummary m) =>
        string.IsNullOrWhiteSpace(m.InternetMessageId)
            ? $"{m.AccountId:N}|{m.FolderName}|{m.MessageId}"
            : $"{m.AccountId:N}|{m.InternetMessageId.Trim().Trim('<', '>').ToLowerInvariant()}";

    private void LoadStored()
    {
        try
        {
            foreach (var (key, choice) in _store!.LoadAll())
                _choices.TryAdd(key, choice);   // a choice made since startup wins; same rules, same answer
        }
        catch (Exception ex)
        {
            LogService.Log($"ContextImageService: stored choices unavailable ({ex.GetType().Name}); continuing in memory.");
        }
    }

    /// <summary>Writes queued choices. Public for tests; normally driven by the debounce timer.</summary>
    public void FlushPendingSaves()
    {
        if (_store is null || Interlocked.Exchange(ref _saving, 1) == 1) return;
        try
        {
            var batch = new List<ContextImageChoice>();
            while (_pendingSaves.TryDequeue(out var c)) batch.Add(c);
            if (batch.Count > 0)
                _store.Save(batch.GroupBy(c => c.MessageKey).Select(g => g.Last()).ToList());
        }
        catch (Exception ex)
        {
            // Losing a write only means the (deterministic) choice is recomputed next time.
            LogService.Log($"ContextImageService: could not save choices ({ex.GetType().Name}).");
        }
        finally
        {
            Interlocked.Exchange(ref _saving, 0);
        }
    }

    public void Dispose()
    {
        _saveTimer.Dispose();
        // Never leave the background load holding the database open past disposal.
        try { _loadTask.Wait(TimeSpan.FromSeconds(5)); } catch (AggregateException) { }
        FlushPendingSaves();
    }
}
