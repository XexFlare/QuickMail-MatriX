<#
.SYNOPSIS
  Opens MailBox MatriX on Xexin's demo mailboxes.
.DESCRIPTION
  1. Starts the local GreenMail test server (127.0.0.1, IMAP 3143 / SMTP 3025) if it is not running.
  2. Seeds the three demo accounts (seed_demo.py) unless they already hold the demo mail.
  3. Creates the demo profile in %LOCALAPPDATA%\MailBoxMatriX-demo (accounts.json, config.ini) and the
     dummy Credential Manager entries the accounts need (GreenMail accepts any password).
  4. Starts MailBox MatriX on that profile. Your real MailBox MatriX data (%AppData%\MailBoxMatriX) is never touched.
.PARAMETER Exe     MailBoxMatriX.exe to run (default: the preview build next to this repository).
.PARAMETER Reset   Wipe and re-seed the demo mail, and recreate the demo profile.
#>
param(
    [string]$Exe = "",
    [switch]$Reset,
    [switch]$NoLaunch      # prepare server, mail and profile only (used for automated checks)
)
$ErrorActionPreference = 'Stop'
$repo = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
if (-not $Exe) { $Exe = Join-Path $repo 'preview\app\MailBoxMatriX.exe' }
if (-not (Test-Path $Exe)) { throw "MailBox MatriX not found at $Exe" }

function Test-Port([int]$port) {
    $client = New-Object System.Net.Sockets.TcpClient
    try { $client.Connect('127.0.0.1', $port); return $true } catch { return $false } finally { $client.Dispose() }
}

# ── 1. GreenMail ──────────────────────────────────────────────────────────────
if (-not (Test-Port 3143)) {
    $jar = Join-Path $repo '.testservers\greenmail-standalone-2.1.11.jar'
    $java = Join-Path $env:LOCALAPPDATA 'MailBoXX-devtools\jdk\bin\java.exe'
    if (-not (Test-Path $java)) { $java = (Get-Command java -ErrorAction SilentlyContinue).Source }
    if (-not (Test-Path $jar)) { throw "GreenMail jar missing ($jar). Run scripts\start-test-servers.ps1 once to download it." }
    if (-not $java) { throw "Java not found. See docs\MAILBOXX_BUILD.md." }
    Write-Host "Starting the local demo mail server (GreenMail)..."
    # No output redirection: a redirected child inherits this script's handles, which keeps any
    # pipe reading this script open for as long as the server runs.
    Start-Process -FilePath $java -WindowStyle Hidden -ArgumentList @(
        '-Dgreenmail.setup.test.smtp', '-Dgreenmail.setup.test.imap', '-Dgreenmail.setup.test.pop3',
        '-Dgreenmail.auth.disabled', '-jar', "`"$jar`"") | Out-Null
    $deadline = (Get-Date).AddSeconds(60)
    while (-not (Test-Port 3143)) {
        if ((Get-Date) -gt $deadline) { throw "GreenMail did not start within 60 s." }
        Start-Sleep -Milliseconds 500
    }
}

# ── 2. Demo mail ──────────────────────────────────────────────────────────────
$seed = Join-Path $PSScriptRoot 'seed_demo.py'
$pyArgs = @('-I', $seed); if ($Reset) { $pyArgs += '--reset' }
& python @pyArgs
if ($LASTEXITCODE -ne 0) { throw "Seeding the demo mail failed." }

# ── 3. Demo profile ───────────────────────────────────────────────────────────
$profileDir = Join-Path $env:LOCALAPPDATA 'MailBoxMatriX-demo'
if ($Reset -and (Test-Path $profileDir)) { Remove-Item -Recurse -Force $profileDir }
New-Item -ItemType Directory -Force $profileDir | Out-Null

$accounts = @(
    @{ Id = 'de300a1a-0000-4000-8000-000000000001'; AccountName = 'Outlook'; Username = 'xexin@outlook.test' },
    @{ Id = 'de300a1a-0000-4000-8000-000000000002'; AccountName = 'Gmail';   Username = 'xexin.plays@gmail.test' },
    @{ Id = 'de300a1a-0000-4000-8000-000000000003'; AccountName = 'Hotmail'; Username = 'xexin@hotmail.test' }
)

$accountsFile = Join-Path $profileDir 'accounts.json'
if (-not (Test-Path $accountsFile)) {
    $list = foreach ($a in $accounts) {
        [ordered]@{
            Id = $a.Id; AccountName = $a.AccountName; DisplayName = 'Xexin'; Username = $a.Username
            LoginUsername = $null; AuthType = 0; BackendKind = 0; ProviderId = $null
            ImapHost = '127.0.0.1'; ImapPort = 3143; ImapUseSsl = $false; ImapAcceptInvalidCert = $false
            Pop3Host = ''; Pop3Port = 995; Pop3UseSsl = $true; Pop3AcceptInvalidCert = $false; Pop3LeaveMailOnServer = $true
            SmtpHost = '127.0.0.1'; SmtpPort = 3025; SmtpUseSsl = $false; SmtpAcceptInvalidCert = $false
            RequireStartTls = $false; IsDefault = ($a.AccountName -eq 'Outlook'); SyncContacts = $false; SyncCalendar = $false
            Signature = ''; ArchiveFolderFullName = 'Archive'; IsShared = $false; ParentAccountId = $null
            SharedAddress = $null; NotifyOnNewMail = $false
        }
    }
    $json = ConvertTo-Json -InputObject @($list) -Depth 4
    [System.IO.File]::WriteAllText($accountsFile, $json, (New-Object System.Text.UTF8Encoding $false))
}

$configFile = Join-Path $profileDir 'config.ini'
if (-not (Test-Path $configFile)) {
    $ini = @(
        '# MailBox MatriX demo profile (generated by scripts\mailboxx-demo\Run-Demo.ps1)',
        '[global]',
        'ProfileDisplayName = Xexin',
        'TutorialCompleted = on',
        'DesktopShortcutPrompted = on',
        'AutoUpdate = off',
        'SyncDays = 30',
        'NotifyOnNewMail = off',
        'ContextImages = on',
        'AppearanceThemeId = system'
    )
    [System.IO.File]::WriteAllLines($configFile, $ini, (New-Object System.Text.UTF8Encoding $false))
}

foreach ($a in $accounts) {
    # Dummy password: the demo server accepts anything. Stored where MailBox MatriX expects account passwords.
    cmdkey /generic:"MailBoxMatriX:$($a.Id)" /user:$($a.Username) /pass:demo | Out-Null
}

# ── 4. Start MailBox MatriX ─────────────────────────────────────────────────────────
if ($NoLaunch) { Write-Host "Demo ready: $profileDir"; return }
Write-Host "Opening MailBox MatriX on the demo profile ($profileDir)..."
Start-Process -FilePath $Exe -ArgumentList @('--profileDir', "`"$profileDir`"")
